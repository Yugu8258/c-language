#include <stdio.h>

int main(void)
{
    // long 
    long number_1 = 123l;

    printf("number_1 = %ld\n", number_1);

    // unsigned long
    unsigned long number_2 = 456l;

    printf("number_2 = %lu\n", number_2);

    // long long
    long long number_3 = 123l;

    printf("number_3 = %lld\n", number_3);

    // unsigned long long
    unsigned long long number_4 = 456l;

    printf("number_4 = %llu\n", number_4);

    return 0;
}

